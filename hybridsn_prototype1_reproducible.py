# 13. PROTOTYPE 1A
# =========================
class HybridSN_LightDense(nn.Module):
    def __init__(self, in_chs, patch_size, class_nums, pool_size=(2, 2)):
        super().__init__()

        self.in_chs = in_chs
        self.patch_size = patch_size
        self.pool_size = pool_size

        # Keep the HybridSN 3D feature extractor unchanged.
        self.conv1 = nn.Sequential(
            nn.Conv3d(1, 8, kernel_size=(7, 3, 3)),
            nn.ReLU(inplace=True)
        )

        self.conv2 = nn.Sequential(
            nn.Conv3d(8, 16, kernel_size=(5, 3, 3)),
            nn.ReLU(inplace=True)
        )

        self.conv3 = nn.Sequential(
            nn.Conv3d(16, 32, kernel_size=(3, 3, 3)),
            nn.ReLU(inplace=True)
        )

        self.x1_shape = self.get_shape_after_3dconv()

        # Keep HybridSN 2D convolution unchanged.
        self.conv4 = nn.Sequential(
            nn.Conv2d(
                self.x1_shape[1] * self.x1_shape[2],
                64,
                kernel_size=(3, 3)
            ),
            nn.ReLU(inplace=True)
        )

        # Experimental change: spatial pooling.
        self.pool = nn.AdaptiveAvgPool2d(pool_size)

        self.x2_shape = self.get_shape_after_2dconv()

        # Lightweight dense classifier.
        self.dense1 = nn.Sequential(
            nn.Linear(self.x2_shape, 128),
            nn.ReLU(inplace=True),
            nn.Dropout(p=0.4)
        )

        self.dense2 = nn.Sequential(
            nn.Linear(128, 64),
            nn.ReLU(inplace=True),
            nn.Dropout(p=0.4)
        )

        self.dense3 = nn.Linear(64, class_nums)

    def get_shape_after_3dconv(self):
        x = torch.zeros(
            1, 1, self.in_chs, self.patch_size, self.patch_size
        )
        with torch.no_grad():
            x = self.conv1(x)
            x = self.conv2(x)
            x = self.conv3(x)
        return x.shape

    def get_shape_after_2dconv(self):
        x = torch.zeros(
            1,
            self.x1_shape[1] * self.x1_shape[2],
            self.x1_shape[3],
            self.x1_shape[4]
        )
        with torch.no_grad():
            x = self.conv4(x)
            x = self.pool(x)
        return x.shape[1] * x.shape[2] * x.shape[3]

    def forward(self, X):
        X = X.unsqueeze(1)

        x = self.conv1(X)
        x = self.conv2(x)
        x = self.conv3(x)

        x = x.view(
            x.shape[0],
            x.shape[1] * x.shape[2],
            x.shape[3],
            x.shape[4]
        )

        x = self.conv4(x)
        x = self.pool(x)

        x = x.contiguous().view(x.shape[0], -1)

        x = self.dense1(x)
        x = self.dense2(x)

        return self.dense3(x)

