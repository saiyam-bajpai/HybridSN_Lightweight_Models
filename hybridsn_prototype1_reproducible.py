# 15. GENERIC TRAINING FUNCTION
# =========================

def train_model(
    model_class,
    model_kwargs,
    seed=RANDOM_SEED,
    save_name=None
):
    """
    Train a model using:
        Training set      -> update weights
        Validation set    -> select best epoch
        Test set          -> final evaluation only

    The test set is NEVER used during training.
    """

    # -------------------------------------------------
    # 1. Reset random states
    # -------------------------------------------------
    set_seed(seed)

    # -------------------------------------------------
    # 2. Create fresh deterministic DataLoaders
    # -------------------------------------------------
    train_loader, val_loader, test_loader = make_loaders(seed)

    # -------------------------------------------------
    # 3. Create model AFTER resetting seed
    # -------------------------------------------------
    model = model_class(**model_kwargs).to(device)

    # -------------------------------------------------
    # 4. Loss + optimizer
    # -------------------------------------------------
    criterion = nn.CrossEntropyLoss()

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=LR,
        weight_decay=WEIGHT_DECAY
    )

    # -------------------------------------------------
    # 5. History
    # -------------------------------------------------
    train_losses = []
    train_accs = []

    val_accs = []
    val_losses = []

    best_val_accuracy = -1.0
    best_epoch = -1
    best_state_dict = None

    # -------------------------------------------------
    # 6. Training
    # -------------------------------------------------
    start_time = time.time()

    for epoch in range(EPOCHS):

        # =============================================
        # TRAIN
        # =============================================
        model.train()

        running_loss = 0.0
        correct = 0
        total = 0

        for data_batch, target in train_loader:

            data_batch = data_batch.to(device)
            target = target.to(device)

            optimizer.zero_grad(set_to_none=True)

            output = model(data_batch)

            loss = criterion(
                output,
                target
            )

            loss.backward()
            optimizer.step()

            running_loss += (
                loss.item()
                * data_batch.size(0)
            )

            predictions = output.argmax(
                dim=1
            )

            correct += (
                predictions == target
            ).sum().item()

            total += target.size(0)

        epoch_train_loss = (
            running_loss / total
        )

        epoch_train_accuracy = (
            correct / total
        )

        # =============================================
        # VALIDATION
        # =============================================
        model.eval()

        val_running_loss = 0.0
        val_correct = 0
        val_total = 0

        with torch.no_grad():

            for data_batch, target in val_loader:

                data_batch = data_batch.to(device)
                target = target.to(device)

                output = model(data_batch)

                loss = criterion(
                    output,
                    target
                )

                val_running_loss += (
                    loss.item()
                    * data_batch.size(0)
                )

                predictions = output.argmax(
                    dim=1
                )

                val_correct += (
                    predictions == target
                ).sum().item()

                val_total += target.size(0)

        epoch_val_loss = (
            val_running_loss / val_total
        )

        epoch_val_accuracy = (
            val_correct / val_total
        )

        # =============================================
        # SAVE HISTORY
        # =============================================
        train_losses.append(
            epoch_train_loss
        )

        train_accs.append(
            epoch_train_accuracy
        )

        val_losses.append(
            epoch_val_loss
        )

        val_accs.append(
            epoch_val_accuracy
        )

        # =============================================
        # BEST VALIDATION MODEL
        # =============================================
        if epoch_val_accuracy > best_val_accuracy:

            best_val_accuracy = (
                epoch_val_accuracy
            )

            best_epoch = epoch

            # Store a CPU copy of the best model.
            best_state_dict = {
                key: value.detach().cpu().clone()
                for key, value in model.state_dict().items()
            }

        # =============================================
        # PROGRESS
        # =============================================
        print(
            f"Epoch {epoch+1:03d}/{EPOCHS} | "
            f"Loss: {epoch_train_loss:.4f} | "
            f"Train Acc: "
            f"{epoch_train_accuracy*100:.2f}% | "
            f"Val Loss: {epoch_val_loss:.4f} | "
            f"Val Acc: "
            f"{epoch_val_accuracy*100:.2f}%"
        )

    # -------------------------------------------------
    # 7. Restore BEST validation model
    # -------------------------------------------------
    model.load_state_dict(
        best_state_dict
    )

    model = model.to(device)

    # -------------------------------------------------
    # 8. FINAL TEST EVALUATION
    # -------------------------------------------------
    model.eval()

    test_correct = 0
    test_total = 0

    with torch.no_grad():

        for data_batch, target in test_loader:

            data_batch = data_batch.to(device)
            target = target.to(device)

            output = model(data_batch)

            predictions = output.argmax(
                dim=1
            )

            test_correct += (
                predictions == target
            ).sum().item()

            test_total += target.size(0)

    final_test_accuracy = (
        test_correct / test_total
    )

    # -------------------------------------------------
    # 9. Training time
