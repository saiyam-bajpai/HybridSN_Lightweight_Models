def extract_patches(coords, padded_data, patch_size):

    half = patch_size // 2
    patches = []

    for row, col in coords:

        row_p = row + half
        col_p = col + half

        patch = padded_data[
            row_p-half:row_p+half+1,
            col_p-half:col_p+half+1,
            :
        ]

        patches.append(patch)

    return np.asarray(patches)


