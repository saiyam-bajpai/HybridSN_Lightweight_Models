def measure_gpu_memory(model):

    model = model.to(device)
    model.eval()

    dummy_input = torch.randn(
        1,
        N_PCA,
        PATCH_SIZE,
        PATCH_SIZE
    ).to(device)

    torch.cuda.empty_cache()
    torch.cuda.reset_peak_memory_stats()

    with torch.no_grad():

        _ = model(dummy_input)

    torch.cuda.synchronize()

    peak_memory = (
        torch.cuda.max_memory_allocated()
        / (1024 ** 2)
    )

    return peak_memory

