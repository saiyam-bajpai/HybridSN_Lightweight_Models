def evaluate_classification(
    model,
    test_loader,
    device
):

    model.eval()

    all_predictions = []
    all_targets = []

    with torch.no_grad():

        for data_batch, target in test_loader:

            data_batch = data_batch.to(device)

            output = model(data_batch)

            predictions = output.argmax(
                dim=1
            )

            all_predictions.extend(
                predictions.cpu().numpy()
            )

            all_targets.extend(
                target.numpy()
            )

    all_predictions = np.asarray(
        all_predictions
    )

    all_targets = np.asarray(
        all_targets
    )

    # -------------------------
    # Confusion Matrix
    # -------------------------

    cm = confusion_matrix(
        all_targets,
        all_predictions,
        labels=np.arange(NUM_CLASS)
    )

    # -------------------------
    # Overall Accuracy
    # -------------------------

    OA = (
        np.trace(cm)
        /
        np.sum(cm)
    )

    # -------------------------
    # Per-class Accuracy
    # -------------------------

    with np.errstate(
        divide="ignore",
        invalid="ignore"
    ):

        class_accuracy = (
            np.diag(cm)
            /
            cm.sum(axis=1)
        )

    # -------------------------
    # Average Accuracy
    # -------------------------

    AA = np.nanmean(
        class_accuracy
    )

    # -------------------------
    # Kappa
    # -------------------------

    Kappa = cohen_kappa_score(
        all_targets,
        all_predictions
    )

    return (
        cm,
        OA,
        AA,
        Kappa,
        class_accuracy
    )


